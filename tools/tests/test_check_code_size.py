"""tools/check_code_size.py のテスト。実行: backend の venv の Python で python -m pytest tools/tests(リポジトリ直下)。"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import check_code_size as c  # noqa: E402

PY_SAMPLE = '''"""モジュールの説明。
2行目。
"""
# コメントだけの行
x = 1  # 行末のコメントは数えない
s = """文字列(docstring ではない)"""


class A:
    """クラスの説明。"""


def f():
    """関数の説明。"""
    return 1
'''


def test_python_docstrings_and_full_line_comments_are_counted():
    assert sorted(c._python_comment_lines(PY_SAMPLE)) == [1, 2, 3, 4, 10, 14]


def test_python_trailing_comment_is_not_counted():
    assert c._python_comment_lines("x = 1  # 行末\ny = 2\n") == set()


def test_ts_and_jsx_comments():
    ts = (
        "// 行コメント\n"
        "const a = 1; // 行末は数えない\n"
        "/* ブロック\n"
        "   の続き */\n"
        "const b = <div>{/* 行の途中の JSX のコメント */}</div>;\n"
        "{/* JSX の行コメント */}\n"
        "/** 1行のブロック */\n"
        "const c = 3;\n"
    )
    assert sorted(c._ts_comment_lines(ts)) == [1, 3, 4, 6, 7]


def test_long_function_is_detected():
    src = "def g():\n" + "    x = 1\n" * 60 + "\n\ndef short():\n    return 1\n"
    assert c._python_long_functions(src) == [("g", 61)]


def test_function_of_exactly_limit_lines_is_ok():
    src = "def g():\n" + "    x = 1\n" * (c.FUNCTION_LIMIT - 1)
    assert c._python_long_functions(src) == []


def test_app_file_over_400_needs_split():
    stat = c.FileStat("backend/app/x.py", False, 401, 300, 10)
    assert stat.needs_split
    assert stat.findings() == ["要分割(400行超)"]


def test_app_file_over_300_is_warned_but_not_split():
    stat = c.FileStat("backend/app/x.py", False, 301, 250, 10)
    assert not stat.needs_split
    assert stat.findings() == ["300行超"]


def test_test_file_over_500_is_warned_but_not_split():
    stat = c.FileStat("backend/tests/test_x.py", True, 501, 400, 10)
    assert not stat.needs_split
    assert stat.findings() == ["テストが500行超(テーマごとに分ける)"]


def test_comment_ratio_is_checked_only_for_files_with_enough_lines():
    assert c.FileStat("backend/app/small.py", False, 10, 8, 6).findings() == []
    assert c.FileStat("backend/app/big.py", False, 40, 30, 10).findings() == ["コメント 33%"]


def _write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def test_collect_excludes_migrations_and_generated_files(tmp_path):
    _write(tmp_path, "backend/app/a.py", "x = 1\n")
    _write(tmp_path, "backend/app/db/migrations/versions/0001_x.py", "x = 1\n")
    _write(tmp_path, "backend/app/gen.py", "# @generated by a tool\nx = 1\n")
    _write(tmp_path, "backend/tests/test_a.py", "def test_a():\n    pass\n")
    _write(tmp_path, "frontend/src/api/schema.ts", "export type A = 1;\n")
    _write(tmp_path, "frontend/src/other/auto.ts", "// このファイルは自動生成です\nexport const a = 1;\n")
    _write(tmp_path, "frontend/src/vite-env.d.ts", "/// <reference />\n")
    _write(tmp_path, "frontend/src/field/A.tsx", "export const A = () => null;\n")
    _write(tmp_path, "frontend/src/shared/x.test.ts", "test('x', () => {});\n")
    _write(tmp_path, "frontend/src/shared/readme.md", "# 対象外の拡張子\n")

    stats = {s.path: s for s in c.collect(tmp_path)}

    assert sorted(stats) == [
        "backend/app/a.py", "backend/tests/test_a.py", "frontend/src/field/A.tsx", "frontend/src/shared/x.test.ts",
    ]
    assert stats["backend/tests/test_a.py"].is_test and stats["frontend/src/shared/x.test.ts"].is_test
    assert not stats["frontend/src/field/A.tsx"].is_test


def test_main_returns_1_when_split_is_needed(tmp_path, capsys):
    _write(tmp_path, "backend/app/huge.py", "x = 1\n" * 401)
    assert c.main([], root=tmp_path) == 1
    assert "要分割: 1 件" in capsys.readouterr().out


def test_main_returns_0_without_split(tmp_path, capsys):
    _write(tmp_path, "backend/app/ok.py", "x = 1\n" * 10)
    assert c.main(["--top", "1"], root=tmp_path) == 0
    out = capsys.readouterr().out
    assert "要分割: なし" in out and "backend/app/ok.py" in out
